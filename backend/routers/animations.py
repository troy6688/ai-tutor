class AnimationRequest(BaseModel):
    template: str
    knowledge_point_id: int
    title: Optional[str] = ""
    values: List[int] = Field(default_factory=list)
    grade: Optional[str] = "小学高年级"
    theme: Optional[str] = "light"
    narration: Optional[bool] = False


@router.post("/preview")
def preview(req: AnimationRequest):
    """校验模板归属并返回动画场景配置。"""
    point = get_point(req.knowledge_point_id)
    if point is None:
        raise HTTPException(status_code=404, detail="知识点不存在")
    if req.template not in ALLOWED_TEMPLATES:
        raise HTTPException(status_code=422, detail="不支持的动画模板")
    if point.get("animation") != req.template:
        raise HTTPException(status_code=422, detail="该知识点没有配套的互动动画")

    values = [int(v) for v in req.values if str(v).strip().lstrip("-").isdigit()] if req.values else []
    if not values:
        values = [9, 1, 7, 3, 2]
    values = values[:12]

    return {
        "code": 0,
        "message": "ok",
        "data": {
            "template": req.template,
            "knowledge_point_id": req.knowledge_point_id,
            "title": TEMPLATE_TITLES.get(req.template, req.title or point.get("title", "")),
            "values": values,
            "grade": req.grade or point.get("grade", ""),
        },
    }
